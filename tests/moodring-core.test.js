"use strict";
const assert = require("assert");
const fs = require("fs");
const { MOODRING_LABELS, validatedModel, compareMoodring } = require("../src/moodring-core");
const terms = ["happy","sad","very happy","very sad"], n = terms.length, k = MOODRING_LABELS.length;
const meta = {n_features:n, terms, emotions:MOODRING_LABELS, thresholds:Array(k).fill(0.5), intercept:Array(k).fill(-5)};
meta.intercept[MOODRING_LABELS.indexOf("joy")] = -1;
meta.intercept[MOODRING_LABELS.indexOf("sadness")] = -1;
const json = Buffer.from(JSON.stringify(meta)), bytes = Buffer.alloc(13+json.length+4*n*(k+1));
bytes.write("MOODRING1",0);bytes.writeUInt32LE(json.length,9);json.copy(bytes,13);
for(let i=0;i<n;i++) bytes.writeFloatLE(1,13+json.length+4*i);
bytes.writeFloatLE(6,13+json.length+4*(n+n*MOODRING_LABELS.indexOf("joy")));
bytes.writeFloatLE(6,13+json.length+4*(n+n*MOODRING_LABELS.indexOf("sadness")+1));
const model = validatedModel(bytes);
assert.deepStrictEqual(compareMoodring(model,"happy").labels.map(x=>x.label),["joy"]);
assert.deepStrictEqual(compareMoodring(model,"sad").labels.map(x=>x.label),["sadness"]);
assert.strictEqual(compareMoodring(model,"unknown words").abstained,true);
assert.strictEqual(compareMoodring(model,""),null);
const longer=compareMoodring(model,"happy ".repeat(3000));
assert(longer.truncated && longer.coveredChars===12000);
const bad=Buffer.from(bytes);bad.write("INVALID!!",0);
assert.throws(()=>validatedModel(bad),/magic/);
assert.throws(()=>validatedModel(bytes.subarray(0, bytes.length-1)),/shape/);
const bundled=fs.readFileSync(require("path").join(__dirname,"../main.js"),"utf8");
assert(bundled.includes("MOODRING_VERSION") && bundled.includes("compareMoodring"));
console.log("Moodring independent offline model tests passed");
